#!/usr/bin/env python3
"""Build web/index.html and web/app/menu.js from frescokart-landing.html.

frescokart-landing.html is the page exactly as it is published as an artifact. This adds what a real
website needs around it (doctype, language, viewport, icon, description) and writes web/index.html,
which server/app.py serves.

The menu (fish, kits, prices, offers, what is inside each kit and the cooking steps) lives in that page's
script. This also copies it into web/app/menu.js, so the app at /app/ always sells the same things at the
same prices. Run it after every change to frescokart-landing.html:

  python build_site.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "frescokart-landing.html"
OUT = ROOT / "web" / "index.html"
MENU = ROOT / "web" / "app" / "menu.js"

DESCRIPTION = ("Ready-to-cook Kerala fish kits: fresh fish, cut vegetables and measured masalas in one chilled pack, "
               "with the cooking steps in the app. Order now in Kochi, delivered in about 45 minutes.")

HEAD = (
    '<!doctype html>\n<html lang="en">\n'
    '<meta charset="utf-8">\n'
    '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n'
    '<meta name="theme-color" content="#006B48">\n'
    '<meta name="description" content="%s">\n'
    '<meta property="og:type" content="website">\n'
    '<meta property="og:title" content="FrescoKart: the whole dish, ready to cook">\n'
    '<meta property="og:description" content="%s">\n'
    '<link rel="icon" href="img/symbol-colour.svg" type="image/svg+xml">\n' % (DESCRIPTION, DESCRIPTION)
)


def menu_js(page):
    start = page.index("var fish=[")
    end = page.index("];", page.index("var kits=[")) + 2
    return ("/* Made by build_site.py from the menu in frescokart-landing.html. Change the menu there, then run\n"
            "   python build_site.py. Do not edit this file by hand. */\n"
            "(function(){\n" + page[start:end] + "\nwindow.FK_MENU={fish:fish,kits:kits};\n})();\n")


def main():
    page = SRC.read_text(encoding="utf-8")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEAD + page + "\n</html>\n", encoding="utf-8")
    print("wrote", OUT)
    MENU.parent.mkdir(parents=True, exist_ok=True)
    MENU.write_text(menu_js(page), encoding="utf-8")
    print("wrote", MENU)


if __name__ == "__main__":
    main()
